// 跨组冲突：同名以先处理的组为准（m > f > n），后者丢弃
const taken = new Set();
function dedupeCross(r) {
  const kept = [];
  for (const ch of r.added) {
    if (taken.has(ch)) { r.dropped.push([ch, '跨组冲突']); continue; }
    taken.add(ch);
    kept.push(ch);
  }
  r.added = kept;
}
