/** 单组新增字机器校验：返回 { ok, added, dropped } */
function validateAndDedup(rawList, groupName) {
  const added = [];
  const dropped = [];
  const claimed = new Set();
  for (const ch of rawList) {
    if (claimed.has(ch)) continue; // 组内去重
    claimed.add(ch);
    if (existingAll.has(ch) || added.some((x) => x === ch)) { dropped.push([ch, '已在池中']); continue; }
    if (!coreSet.has(ch)) { dropped.push([ch, '不在 hanzi-core']); continue; }
    if (!wlSet.has(ch)) { dropped.push([ch, '不在白名单']); continue; }
    if (blockSet.has(ch)) { dropped.push([ch, '命中黑名单']); continue; }
    if (redlineSingleSet.has(ch)) { dropped.push([ch, '红线单字']); continue; }
    added.push(ch);
  }
  return { ok: true, added, dropped, groupName };
}

