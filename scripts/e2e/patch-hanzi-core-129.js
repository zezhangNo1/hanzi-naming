// ---- 校验表 ----
const VALID_TAGS = ['品德', '言信', '温柔', '心性', '家宅', '刚毅', '文采', '高远', '灵动',
  '音律', '自然', '水泽', '光亮', '丰茂', '山岳', '美玉', '力量', '草木'];
const redlineWords = JSON.parse(fs.readFileSync(path.join(ROOT, 'database/redline-llm.json'), 'utf8')).words;

const core = JSON.parse(fs.readFileSync(path.join(ROOT, 'database/hanzi-core.json'), 'utf8'));
const strokesLib = JSON.parse(fs.readFileSync(path.join(ROOT, 'database/hanzi-strokes.json'), 'utf8'));
const coreSet = new Set(core.chars.map((c) => c.char));

const problems = [];
const newEntries = [];
for (const ch of Object.keys(TABLE)) {
  const [meaning, tags, freq] = TABLE[ch];
  if (coreSet.has(ch)) problems.push(ch + ': 已在 hanzi-core（不在本次 129 清单预期内）');
  if (Array.from(meaning).length > 12) problems.push(ch + ': 释义超 12 字「' + meaning + '」');
  for (const t of tags) if (VALID_TAGS.indexOf(t) === -1) problems.push(ch + ': 非法标签 ' + t);
  for (const w of redlineWords) if (meaning.includes(w)) problems.push(ch + ': 释义命中红线词 ' + w);
  const s = strokesLib.chars[ch];
  if (!s) { problems.push(ch + ': hanzi-strokes 无音形数据'); continue; }
  newEntries.push({
    char: ch,
    strokes: s.strokes,
    pinyin: s.pinyin,
    tone: s.tone,
    freqLevel: freq,
    imageryTags: tags,
    meaning: meaning
  });
}

// 129 清单交叉核对（与 solver 占位清单一致）
const pool = JSON.parse(fs.readFileSync(path.join(ROOT, 'database/name-pool.json'), 'utf8'));
const poolAll = [...new Set([...pool.chars.m, ...pool.chars.f, ...pool.chars.n])];
const missingAfter = poolAll.filter((ch) => !coreSet.has(ch) && !TABLE[ch]);
if (missingAfter.length) problems.push('补全后池字仍缺元数据: ' + missingAfter.join(''));
const tableExtra = Object.keys(TABLE).filter((ch) => !poolAll.includes(ch));
if (tableExtra.length) problems.push('表内非池字: ' + tableExtra.join(''));

if (problems.length) {
  console.error('❌ 校验失败：');
  problems.forEach((p) => console.error('  - ' + p));
  process.exit(1);
}

// ---- 写入（追加到 chars 末尾，更新 total 与版本注记）----
core.chars = core.chars.concat(newEntries);
core.metadata.total = core.chars.length;
core.metadata.version = '粗标 v0 + v0.3 池字补全（129 字人工释义），构建于 2026-09-11';

const outA = path.join(ROOT, 'database/hanzi-core.json');
const outB = path.join(ROOT, 'cloudfunctions/generate/data/hanzi-core.json');
const text = JSON.stringify(core, null, 2) + '\n';
fs.writeFileSync(outA, text, 'utf8');
fs.writeFileSync(outB, text, 'utf8');

const same = fs.readFileSync(outA, 'utf8') === fs.readFileSync(outB, 'utf8');
console.log('✅ 补全 ' + newEntries.length + ' 字，total=' + core.metadata.total + '，双份 diff ' + (same ? '一致' : '不一致！'));
if (!same) process.exit(1);
console.log('样例：' + newEntries.slice(0, 3).map((e) => e.char + '=' + e.meaning).join('；'));
